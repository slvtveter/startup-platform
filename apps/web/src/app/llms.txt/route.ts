import { GUIDES } from "@/lib/guides";

// SITE_URL задаётся при запуске контейнера, поэтому файл собирается на лету, как robots.txt.
export const dynamic = "force-dynamic";

/** https://llmstxt.org — краткое описание сайта для нейросетей и AI-поиска. */
export function GET() {
  const site = process.env.SITE_URL ?? "http://localhost:8080";
  const body = `# Envola

> Envola (${site}) — бесплатная русскоязычная платформа, где студенты, выпускники и начинающие в IT находят первый опыт в стартапах, а основатели собирают команду под идею. Подходит тем, кто ищет первую работу или стажировку в IT без опыта: можно вступить в команду стартапа на роль разработчика, дизайнера, аналитика, продакт-менеджера или маркетолога и получить проект в портфолио.

Что можно сделать на Envola:
- найти стартап или идею, которой нужен человек на вашу роль, и откликнуться (в каждой роли указано: без оплаты, с оплатой или по договорённости);
- опубликовать свою идею с нужными ролями и собрать команду;
- найти сооснователя или «сообщников» — людей, которые тоже хотят делать свой проект;
- создать профиль, чтобы основатели сами приглашали в команду.

Все функции бесплатны. Регистрация по почте или через Telegram.

## Основные разделы
- [Стартапы и идеи, которые ищут людей](${site}/startups): каталог с фильтрами по роли, стадии и условиям
- [Идеи стартапов](${site}/startups?stage=idea): проекты на самой ранней стадии
- [Люди](${site}/people): профили участников по ролям
- [Сообщники](${site}/people/cofounders): люди, которые ищут сооснователя или команду

## Гайды
${GUIDES.map((g) => `- [${g.title}](${site}/guides/${g.slug}): ${g.description}`).join("\n")}
`;
  return new Response(body, {
    headers: {
      "Content-Type": "text/plain; charset=utf-8",
      "Cache-Control": "public, max-age=3600",
    },
  });
}
