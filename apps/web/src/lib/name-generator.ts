/**
 * Генератор дурацких названий для стартапа (KAN-138 п.4): чтобы не залипать на шаге «название».
 * Всё на фронте, без внешних сервисов. Прилагательные и существительные одного рода (мужского),
 * чтобы не согласовывать окончания.
 */

const ADJ = [
  "Бодрый", "Ленивый", "Хитрый", "Летучий", "Квантовый", "Хрустящий", "Сонный", "Дерзкий",
  "Пушистый", "Весёлый", "Стальной", "Карманный", "Космический", "Тёплый", "Шустрый", "Мятный",
  "Лунный", "Громкий", "Тихий", "Ночной", "Жёлтый", "Бархатный", "Дикий", "Добрый",
];

const NOUN = [
  "Енот", "Пельмень", "Кактус", "Бублик", "Тапок", "Барсук", "Огурец", "Чайник",
  "Ёж", "Кабачок", "Сухарик", "Пингвин", "Валенок", "Батон", "Хомяк", "Вареник",
  "Утюг", "Пончик", "Карась", "Самовар", "Блинчик", "Крокодил", "Тюлень", "Фикус",
];

const SUFFIX = ["Хаб", "Лаб", "Бот", "Маркет", "Флоу", "Тех", "Клуб", "Сфера", "Шеринг", "Гид"];

const pick = <T>(list: readonly T[]) => list[Math.floor(Math.random() * list.length)];

export function generateName(): string {
  return Math.random() < 0.5 ? `${pick(ADJ)} ${pick(NOUN).toLowerCase()}` : `${pick(NOUN)}${pick(SUFFIX)}`;
}

/** Несколько разных вариантов сразу — из них удобнее выбирать. */
export function generateNames(count = 3): string[] {
  const out = new Set<string>();
  while (out.size < count) out.add(generateName());
  return [...out];
}
